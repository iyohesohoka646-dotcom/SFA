import { test, expect } from '@playwright/test';
import { session } from './session';
import { bindProbe, chooseExample, chooseValue, runCompute, selectObject } from './scientific-helpers';

let savedConfiguration: any;
test.beforeEach(async ({ request }) => {
  savedConfiguration = await (await request.get('http://127.0.0.1:8879/api/v1/research/workbench/configuration',
    { headers: { Authorization: 'Bearer ' + session } })).json();
});
test.afterEach(async ({ request }) => {
  const url = 'http://127.0.0.1:8879/api/v1/research/workbench/configuration', headers = { Authorization: 'Bearer ' + session };
  const current = await (await request.get(url, { headers })).json();
  expect((await request.put(url, { headers, data: { config: { ...savedConfiguration, revision: current.revision }, expected_revision: current.revision } })).ok()).toBe(true);
});

test('each bound presentation probe has a real independently selectable and collapsible view', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://127.0.0.1:8879/?single=1#session=' + session);
  await chooseExample(page); await runCompute(page); await chooseValue(page, 'X');
  const data = page.locator('.wb-data-pane').filter({ has: page.getByTestId('current-variable').filter({ hasText: /^X$/ }) }).last();
  await expect(data.getByTestId('probe-view')).toHaveCount(1);
  await bindProbe(page, 'view.table', 'X');
  await bindProbe(page, 'view.matrix', 'X');
  const inspector = page.locator('.wb-inspector').filter({ visible: true }).filter({ has: page.locator('.wb-view-toolbar > strong').filter({ hasText: /^探针台$/ }) }).first();
  await inspector.getByRole('button', { name: '保存', exact: true }).click();
  await expect(data.getByTestId('probe-view')).toHaveCount(3);
  await data.getByRole('button', { name: '执行探针', exact: true }).click();
  await expect(data.getByTestId('probe-view').locator('summary .wb-kind')).toHaveCount(3);
  await expect(data.getByTestId('probe-view').locator('summary .wb-kind')).toHaveText(['ready', 'ready', 'ready']);
  const table = data.getByTestId('probe-view').filter({ has: page.locator('summary > strong').filter({ hasText: /^数据表$/ }) });
  await expect(table.locator('table')).toBeVisible();
  await expect(table.locator('thead th')).toHaveText(['行号', '0', '1', '2', '3', '4', '5', '6', '7']);
  await expect(data.getByLabel('数据呈现探针')).toHaveCount(0);
  await expect(data.getByTestId('probe-view')).toHaveCount(3);
  await table.locator('summary').click();
  await expect(table.locator('table')).toHaveCount(0);
  await table.locator('summary').click();
  await expect(table.locator('table')).toBeVisible();
  const row = await selectObject(page, 'X');
  expect(await row.locator('.object-dtype').evaluate(element => element.getBoundingClientRect().height)).toBeGreaterThan(12);
  expect(await row.locator('.object-row-name').evaluate(element => element.getBoundingClientRect().width)).toBeGreaterThan(40);
  const before = Number(await row.locator('.object-probe-count').textContent());
  const object = inspector.locator('.probe-object-section').first();
  await expect(object.locator(':scope > summary')).toContainText('X');
  await object.getByLabel('启用 view.table', { exact: true }).uncheck();
  await inspector.getByRole('button', { name: '保存', exact: true }).click();
  await expect(data.getByTestId('probe-view')).toHaveCount(2);
  await expect(row.locator('.object-probe-count')).toHaveText(String(before - 1));
  await page.screenshot({ path: '../docs/assets/compact-probes.png' });
  expect(errors).toEqual([]);
});

test('probe state filters and compact English Code/Data views keep selection and block navigation explicit', async ({ page }) => {
  await page.goto('http://127.0.0.1:8879/?single=1#session=' + session);
  await chooseExample(page, 'analysis', 'summary', ['--failure', 'nan']); await runCompute(page); await chooseValue(page, 'X');
  await bindProbe(page, 'check.finite', 'X');
  await page.locator('.wb-inspector').filter({visible:true}).getByRole('button',{name:'保存',exact:true}).click();
  const data = page.locator('.wb-data-pane').filter({ has: page.getByTestId('current-variable').filter({ hasText: /^X$/ }) }).last();
  await data.getByRole('button', { name: '执行探针', exact: true }).click();
  await expect(data.getByTestId('data-probe-result').filter({ hasText: 'fail' }).first()).toBeVisible();
  await page.getByLabel('对象探针结果').selectOption('failed');
  await expect(page.locator('.object-row-name').filter({ hasText: /^X$/ })).toBeVisible();
  await page.getByLabel('对象探针结果').selectOption('normal');
  await expect(page.locator('.object-row-name').filter({ hasText: /^X$/ })).toHaveCount(0);
  await page.getByLabel('对象探针结果').selectOption('all');
  await page.getByRole('searchbox', { name: '搜索对象', exact: true }).fill('');
  await page.getByRole('button', { name: '计算关系图', exact: true }).first().click();
  await page.getByRole('button', { name: '放大 main 视图', exact: true }).click();
  await expect(page.getByRole('button', { name: '还原 main 视图', exact: true })).toBeVisible();
  const graph = page.locator('.wb-graph-pane');
  await expect(graph).toHaveAttribute('data-layout-state', 'ready');
  await expect(page.getByLabel('关系图视图').locator('option')).toHaveText(['Code', 'Data']);
  await expect(graph.locator('.semantic-node.kind-data')).toHaveCount(0);
  const captions = graph.locator('.semantic-heading strong, .plate-heading strong, .react-flow__edge-text');
  expect((await captions.allTextContents()).every(text => !/[\u3400-\u9fff]|covariance and PCA|未观测/.test(text))).toBe(true);
  expect(await graph.getByTestId('relation-node').count()).toBeLessThan(35);
  await page.getByRole('button', { name: '自动对齐排线', exact: true }).click();
  await expect(graph).toHaveAttribute('data-layout-state', 'ready');
  await page.screenshot({ path: '../docs/assets/compact-code.png' });
  const block = graph.locator('.semantic-plate.kind-condition').first();
  await block.locator('strong').click({ button: 'right' });
  await page.getByRole('button', { name: 'Enter block', exact: true }).click();
  await expect(page.getByRole('button', { name: '返回上级块', exact: true })).toBeEnabled();
  await page.getByRole('button', { name: '返回上级块', exact: true }).click();
  await expect(graph.locator('.semantic-plate.kind-file')).toBeVisible();
  await page.getByRole('button', { name: '返回上级块', exact: true }).click();
  await expect(page.getByRole('button', { name: '返回上级块', exact: true })).toBeDisabled();
  await page.getByLabel('关系图视图').selectOption('data');
  await expect(graph).toHaveAttribute('data-layout-state', 'ready');
  await expect(graph.locator('.semantic-node.kind-data').first()).toBeVisible();
  await expect(graph.locator('.semantic-node.kind-operation, .semantic-node.kind-call')).toHaveCount(0);
  const variables = await graph.locator('.semantic-node.kind-data strong').allTextContents();
  expect(new Set(variables).size).toBe(variables.length);
  await page.getByRole('button', { name: '适应画布', exact: true }).click();
  await page.screenshot({ path: '../docs/assets/compact-data.png' });
});
