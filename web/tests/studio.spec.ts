test('real graph, history, probes, theme and offline export', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  await page.goto('/#session=browser-test-session');
  await expect(page.getByRole('heading', { name: 'Design with clear boundaries.' })).toBeVisible();
  await expect(page.locator('.react-flow__node')).toHaveCount(4);
  await page.getByRole('tab', { name: 'Runs', exact: true }).click();
  await expect(page.getByText('Quality failed', { exact: true })).toBeVisible();
  await expect(page.locator('.timeline-rows button')).toHaveCount(4);
  await page.getByRole('button', { name: 'Fit graph', exact: true }).click();
  await mkdir('../docs/assets', { recursive: true });
  await page.screenshot({ path: '../docs/assets/studio-runtime.png', fullPage: true });
  await page.getByRole('tab', { name: 'Probes', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Preview rule', exact: true })).toBeVisible();
  await page.getByLabel('Probe expression', { exact: true }).fill('$output.mean <= 5');
  await page.getByLabel('Preview sample', { exact: true }).fill('{"mean": 20, "count": 3}');
  await page.getByRole('button', { name: 'Preview rule', exact: true }).click();
  await expect(page.locator('.preview-result')).toContainText('"status": "fail"');
  await page.getByLabel('Probe kind', { exact: true }).selectOption('capture');
  await page.getByLabel('Probe data pointer', { exact: true }).fill('/password');
  await page.getByLabel('Preview sample', { exact: true }).fill('{"password": 7382941}');
  await page.getByRole('button', { name: 'Preview rule', exact: true }).click();
  await expect(page.locator('.preview-result')).toContainText('[REDACTED]');
  await expect(page.locator('.preview-result')).not.toContainText('7382941');
  await page.getByRole('button', { name: 'Toggle theme' }).click();
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light');
  const downloaded = page.waitForEvent('download');
  await page.getByLabel('Export format').selectOption('html');
  const artifact = await downloaded; const filename = '../.work/browser-offline.html'; await artifact.saveAs(filename);
  await page.goto('file:///' + process.cwd().replaceAll('\\', '/') + '/' + filename);
  await expect(page.locator('[data-node]')).toHaveCount(4);
  await page.getByLabel('Search modules').fill('summarize');
  await expect(page.locator('[data-node].dim')).toHaveCount(3);
  expect(errors).toEqual([]);
});

