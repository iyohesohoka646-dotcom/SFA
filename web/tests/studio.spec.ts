test('large folded graph, Chinese labels and background layout stay interactive', async ({ page }) => {
  const headers = { Authorization: 'Bearer browser-test-session' };
  const current = await (await page.request.get('/api/v1/project', { headers })).json();
  const template = current.project.modules[0];
  const contract = { input: { type: 'object', properties: {}, required: [], additionalProperties: false }, output: { type: 'object', properties: {}, required: [], additionalProperties: false }, examples: [] };
  const groups = Array.from({ length: 30 }, (_, i) => `group_${i}`);
  const modules = groups.flatMap((id, i) => [
    { ...template, id, name: `复合模块 ${i + 1}`, kind: 'composite', symbol: null, contract, outputs: {}, parent: null },
    ...Array.from({ length: 20 }, (_, j) => ({ ...template, id: `${id}_step_${j}`, name: `数据处理 ${i + 1} / ${j + 1}`, parent: id, contract })),
  ]);
  const project = { ...current.project, name: 'Large code structure · 大型折叠图', modules, bindings: [], probes: [], metadata: {} };
  const proposal = await page.request.post('/api/v1/changes/architecture', { headers, data: { project, base_revision: current.revision } });
  expect(proposal.ok()).toBeTruthy();
  const change = await proposal.json(); expect(change.status).toBe('proposed');
  expect((await page.request.post(`/api/v1/changes/${change.id}/accept`, { headers, data: { base_revision: current.revision } })).ok()).toBeTruthy();
  await page.request.put('/api/v1/view', { headers, data: { view: { positions: {}, collapsed: groups, theme: 'dark' }, base_revision: current.view.revision } });
  const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
  const foldedStarted = Date.now(); await page.goto('/#session=browser-test-session');
  await expect(page.locator('.react-flow__node')).toHaveCount(30, { timeout: 30000 });
  const foldedMs = Date.now() - foldedStarted;
  await expect(page.locator('.node-name').first()).toContainText('复合模块');
  const interactionStarted = Date.now();
  await page.keyboard.press('Control+k'); await expect(page.getByLabel('Search modules')).toBeFocused();
  await page.getByLabel('Search modules').fill('复合模块 1');
  await expect(page.locator('.module-node.dimmed')).toHaveCount(19);
  const searchMs = Date.now() - interactionStarted;
  await page.screenshot({ path: '../docs/assets/studio-large-folded.png', fullPage: true });
  const view = await (await page.request.get('/api/v1/project', { headers })).json();
  await page.request.put('/api/v1/view', { headers, data: { view: { positions: {}, collapsed: [], theme: 'dark' }, base_revision: view.view.revision } });
  const expandedStarted = Date.now(); await page.reload();
  await expect(page.locator('.react-flow__node')).toHaveCount(630, { timeout: 40000 });
  const expandedMs = Date.now() - expandedStarted;
  const elapsed = await page.locator('.statusbar').innerText();
  expect(errors).toEqual([]);
  await writeFile('../docs/assets/large-graph-performance.json', JSON.stringify({ total_modules: 630, composite_groups: 30, folded_visible_nodes: 30, folded_load_and_layout_ms: foldedMs, expanded_load_and_layout_ms: expandedMs, search_interaction_ms: searchMs, expanded_footer: elapsed, browser: 'Playwright', reduced_motion: true, measured_at: new Date().toISOString() }, null, 2));
});
